export type ClaveUi = keyof (typeof ui)['es'];

export function t(idioma: Idioma, clave: ClaveUi): string {
  return ui[idioma][clave] ?? ui.es[clave];
}

/** Elige el texto del idioma actual dentro de un objeto { es, pt, en }. */
export function elegir<T>(idioma: Idioma, opciones: Record<Idioma, T>): T {
  return opciones[idioma] ?? opciones.es;
}
